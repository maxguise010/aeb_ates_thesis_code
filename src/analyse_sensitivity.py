_LK = lambda k: float(_MAP.loc[_MAP.key == k, "value"].iloc[0])
TTES_NPV_BASE = _LK("TTES NPV base, case B")   # locked; no ROSIM input, unchanged here
LOCKED = {o: (_LK(f"{LAB[o]} NPV base (mid CAPEX)"), _LK(f"{LAB[o]} LCOH (discounted)")) for o in OPTS}   # check only
RUNS_DIR = C.TEMP_SENS_RUNS


def J(name):
    return json.loads((RUNS_DIR / f"{name}.json").read_text())


def headline():
    ev = C.FCORR_EVALS
    dr = pd.read_csv(C.RES_FCORR / "direct_runs.csv")
    sc = pd.read_csv(C.SCENARIO_RESULTS_THESIS)
    sc = sc[sc.scenario == "base"].set_index("option")
    h = {}
    for o in OPTS:
        base = json.loads((ev / f"{C.tagged(o)}__T__1.00000__1.00000.json").read_text())
        if o == "Bstd":
            b = pd.read_csv(C.RES_FCORR / "bstd_fcorr_v3_R.csv").iloc[0]
            f, q = b.f_corr, b.discharged_mwh_yr
        else:
            r = dr[(dr.config == o) & (dr.setting == "T") & (dr.target == "R7")].iloc[0]
            f, q = r.s_stor_eur_yr / base["s_stor_eur_yr"], r.discharged_mwh_yr
        h[o] = dict(f=f, q=q, s_stor=base["s_stor_eur_yr"] / 1e3, dis_uncal=base["discharged_mwh_yr"],
                    s_flex=sc.loc[o].S_flex, capex=FC.ATES[o]["capex_meur"][1], opex=FC.ATES[o]["opex_keur"])
    return h


def econ(h, s_stor, q, opex=None):
    opex = h["opex"] if opex is None else opex
    s_attr = h["s_flex"] + h["f"] * s_stor
    return s_attr, npv(h["capex"], opex, s_attr), lcoh_discounted(h["capex"] * 1e6, opex * 1e3, q)


def step2(h):
    rows = []
    for o in OPTS:
        hd, dr_ = J(f"head_{C.tagged(o)}"), J(f"derate_{C.tagged(o)}")
        H = h[o]
        s_h, n_h, l_h = econ(H, H["s_stor"], H["q"])
        cases = [("headline", hd, H["s_stor"], H["q"])]
        cases.append(("derated", dr_, dr_["s_stor_eur_yr"] / 1e3, H["q"] * dr_["discharged_mwh_yr"] / hd["discharged_mwh_yr"]))
        if (RUNS_DIR / f"cold_{o}.json").exists():
            c = J(f"cold_{o}")
            cases.append(("cold-well cap 117 m3/h", c, c["s_stor_eur_yr"] / 1e3, H["q"] * c["discharged_mwh_yr"] / hd["discharged_mwh_yr"]))
        for lab, r, s, q in cases:
            s_attr, n, l = econ(H, s, q)
            cap = r["cap_mw"]
            rows.append(dict(option=o, case=lab,
                             cap_mw=(f"{cap[0]:.2f} + {cap[1]:.2f}" if isinstance(cap, list) else f"{cap:.2f}"),
                             cap_total_mw=(sum(cap) if isinstance(cap, list) else cap),
                             s_stor_uncal_keur=s, s_stor_rerun_check_keur=hd["s_stor_eur_yr"] / 1e3 if lab == "headline" else np.nan,
                             change_vs_headline_keur=s - H["s_stor"],
                             change_vs_headline_pct=100 * (s / H["s_stor"] - 1),
                             discharged_uncal_mwh_yr=r["discharged_mwh_yr"],
                             share_discharge_hours_at_cap=r["share_discharge_hours_at_cap"],
                             f_corr_headline=H["f"], s_stor_after_cal_keur=H["f"] * s, s_attr_base_keur=s_attr,
                             npv_base_meur=n, npv_change_meur=n - n_h, q_lcoh_mwh_yr=q, lcoh_eur_mwh=l,
                             lcoh_change=l - l_h, npv_locked=LOCKED[o][0] if lab == "headline" else np.nan,
                             lcoh_locked=LOCKED[o][1] if lab == "headline" else np.nan))
    t = pd.DataFrame(rows)
    t.to_csv(HERE / "step2_derated.csv", index=False, float_format="%.4f")
    rk = []
    for case in ("headline", "derated"):
        d = {o: t[(t.option == o) & (t.case == case)].npv_base_meur.iloc[0] for o in OPTS}
        d["TTES5k"] = TTES_NPV_BASE
        order = sorted(d, key=lambda k: -d[k])
        rk.append(dict(case=case, ranking=" > ".join(LAB[k] for k in order),
                       **{f"npv_{k}": round(v, 2) for k, v in d.items()}))
    rk = pd.DataFrame(rk)
    rk.to_csv(HERE / "step2_ranking.csv", index=False)
    return t, rk


def weekly_T(run):
    """Year-7 weekly warm-well temperature (column T) by calendar week, and the production flag."""
    proj = RUNS[run][0]
    eff, per = au.read_eff_full(proj)
    d = per[[w for w in per if w.startswith("warm")][0]]
    rows = range(au.YEAR_END[5] - 51, au.YEAR_END[5] + 1)          # year 7 = weeks 312..363
    return {w % 52: (float(d["T"].iloc[w]), float(d["Q"].iloc[w])) for w in rows}


def step3_energy():
    p = pd.read_csv(HERE / "rosim_production_temps_y7.csv")
    keep = ["run", "T_prod_vw", "T_prod_min", "T_prod_max", "share_weeks_below_90", "share_energy_below_90",
            "produced_energy_mwh_vs_Tret", "energy_below_90_mwh"]
    p[keep].to_csv(HERE / "step3_energy_below_90.csv", index=False, float_format="%.3f")
    return p[keep]


def cop_carnot50(t_evap, t_cond=95.0):
    return 0.5 * (t_cond + 273.15) / np.maximum(t_cond - t_evap, 1.0)


def hp_case(Q, ta, price, cop, t_ret):
    add = np.where((Q > 1e-9) & (ta < 90.0), Q * (90.0 - ta) / np.maximum(ta - t_ret, 1.0), 0.0)
    w = add / cop
    return add.sum() / 3, w.sum() / 3, float((w * price).sum() / 3 / 1e3)


def step3_hp(h):
    old = pd.read_csv(C.NW_HEAT_PUMP_THESIS)
    thesis_cost = float(old[(old.run == "calibrated") & (old.cop_basis.str.startswith("0.5"))].cost_keur_yr_hourly_epex.iloc[0])
    thesis_wel = float(old[(old.run == "calibrated") & (old.cop_basis.str.startswith("0.5"))].W_el_mwh_yr.iloc[0])
    H = h["Bstd"]
    rows = []
    tnw, twn = weekly_T("B-std NW"), weekly_T("B-std WN")
    y7 = pd.read_csv(HERE / "rosim_production_temps_y7.csv").set_index("run").T_prod_vw
    for run_name, lab in (("bstd_cal" + C.bstd_tag(), "calibrated run (locked f_corr scales)"), ("head_Bstd" + C.bstd_tag(), "uncalibrated run")):
        f = pd.read_pickle(C.TEMP_SENS_HOURLY / f"{run_name}_hourly.pkl")
        woy = np.minimum((f.index.dayofyear - 1) // 7, 51)
        price = f["Prijs_Gemiddelde_EPEX_Spot"].values
        q_nw = f["ates_nieuwwest_discharge_mw"].values
        q_wn = f["ates_westpoort_discharge_mw"].values + f["ates_noord_discharge_mw"].values
        for loop, Q, tw, tp in (("NW", q_nw, tnw, y7["B-std NW"]),
                                ("WN (not in thesis: WN mixes with plant water)", q_wn, twn, y7["B-std WN"])):
            for t_basis, ta in (("weekly ROSIM T, all weeks (thesis method)", np.array([tw[w][0] for w in woy])),
                                (f"ROSIM year-7 production mean {tp:.1f} C", np.full(len(Q), tp))):
                for cop_basis, cop in (("COP 4.38 fixed lift 53->95 C (thesis)", cop_carnot50(53.0)),
                                       ("COP from ROSIM T: evaporator T - 5 C -> 95 C", cop_carnot50(ta - 5.0))):
                    for t_ret in (58.0, 70.0):
                        add, wel, cost = hp_case(Q, ta, price, cop, t_ret)
                        rows.append(dict(run=lab, loop=loop, temperature_basis=t_basis, cop_basis=cop_basis,
                                         ates_heat_counted_above_c=t_ret, discharged_mwh_yr=Q.sum() / 3,
                                         mean_Ta_discharge_weighted=float(np.average(ta, weights=Q + 1e-12)),
                                         share_discharge_below_90=float(Q[ta < 90].sum() / Q.sum()),
                                         heat_added_mwh_yr=add, cop_effective=add / wel if wel > 0 else np.nan,
                                         W_el_mwh_yr=wel, cost_keur_yr=cost))
    t = pd.DataFrame(rows)
    # OPEX / NPV / LCOH effect: replace the 54 k EUR/yr of the locked OPEX by the recomputed NW cost
    s_attr = H["s_flex"] + H["f"] * H["s_stor"]
    t["opex_keur"] = np.where(t.loop == "NW", H["opex"] - 54.0 + t.cost_keur_yr, np.nan)
    t["npv_base_meur"] = [npv(H["capex"], o, s_attr) if o == o else np.nan for o in t.opex_keur]
    t["lcoh_eur_mwh"] = [lcoh_discounted(H["capex"] * 1e6, o * 1e3, H["q"]) if o == o else np.nan for o in t.opex_keur]
    t["thesis_W_el_mwh_yr"], t["thesis_cost_keur_yr"] = thesis_wel, thesis_cost
    t.to_csv(HERE / "step3_heat_pump.csv", index=False, float_format="%.3f")
    return t, s_attr


